#!/usr/bin/env python3
"""Evidence-aware wrapper for the legacy Andreas Ubuntu target gate.

The original gate correctly requires a clean release input, but `git status --porcelain`
counts receipts generated by the immediately preceding V2 collector as dirty source.
This wrapper preserves the exact gate semantics while filtering *only* known generated
evidence/output roots from the cleanliness query. Toolchain/source/config changes still
fail closed.
"""
from __future__ import annotations
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
import claycode_andreas_ubuntu_target_gate as gate

_original_git_text=gate.git_text
_ALLOWED=(
    'research_entity/claycode/autonomous/',
    'research_entity/claycode/target/',
    'research_entity/claycode/target_receipts/',
    'research_entity/claycode/corpus/base_v1/',
    'CLAYCODE_GENERAL_PURPOSE_COMPILER_MANIFEST.json',
)

def _evidence_aware_git_text(*args:str)->str:
    text=_original_git_text(*args)
    if tuple(args)!=('status','--porcelain'):
        return text
    kept=[]
    for line in text.splitlines():
        raw=line[3:] if len(line)>=4 else line
        paths=[x.strip() for x in raw.split(' -> ')]
        if paths and all(any(p.startswith(prefix) for prefix in _ALLOWED) for p in paths):
            continue
        kept.append(line)
    return '\n'.join(kept)

gate.git_text=_evidence_aware_git_text

if __name__=='__main__':
    raise SystemExit(gate.main())
