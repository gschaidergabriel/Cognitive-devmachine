"""Fail-closed surgical edit primitive for Project Frankenstein.

This module does not call models, providers, shells, git, or the network. It
accepts a strict JSON-compatible edit plan and applies only hash-bound,
exact-text replacements to existing UTF-8 files, plus creation of new files.

The design is intentionally narrower than a general patch engine. Existing
files can be changed only when:
- the caller supplies the exact SHA-256 of the current file;
- every old_text span is present exactly once in the staged content;
- the total span replaced is small relative to the exact base file;
- paths stay inside repo_root and do not traverse symlinks;
- the whole plan stages successfully before any write occurs.

This directly addresses the 2026-08-28 Frankenstein counterexample where a
whole-file model rewrite replaced a 672-line file with an 87-line fabrication.
A surgical edit plan cannot silently omit unrelated regions because those
regions are never regenerated by the model and are copied from the verified
base bytes by the deterministic applicator.

Evidence boundary: this is a source primitive. It does not by itself promote
provider, Frankenstein dispatch, HCU, EntityOS, J-Space, or training runtime
credit.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import tempfile
from typing import Any

SCHEMA = "FRANKENSTEIN_SAFE_EDIT_PLAN/v1"
MAX_FILES = 8
MAX_REPLACEMENTS_PER_FILE = 8
MAX_REPLACED_FRACTION = 0.25
MAX_PLAN_BYTES = 1_000_000


class SafeEditError(ValueError):
    """Raised when an edit plan is ambiguous, stale, unsafe, or malformed."""


@dataclass(frozen=True)
class StagedChange:
    relative_path: str
    operation: str
    before: str | None
    after: str
    before_sha256: str | None
    after_sha256: str
    replaced_chars: int
    replaced_fraction: float


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _strict_keys(obj: dict[str, Any], allowed: set[str], context: str) -> None:
    unknown = set(obj) - allowed
    if unknown:
        raise SafeEditError(f"{context}: unknown field(s): {sorted(unknown)}")


def _safe_path(repo_root: Path, rel_path: str) -> Path:
    if not isinstance(rel_path, str) or not rel_path or "\x00" in rel_path:
        raise SafeEditError("path must be a non-empty UTF-8 string without NUL")
    raw = Path(rel_path)
    if raw.is_absolute() or rel_path.startswith(("/", "\\")):
        raise SafeEditError(f"absolute path forbidden: {rel_path}")
    if any(part in ("", ".", "..") for part in raw.parts):
        raise SafeEditError(f"ambiguous/traversal path forbidden: {rel_path}")

    root = repo_root.resolve(strict=True)
    cursor = root
    for part in raw.parts[:-1]:
        cursor = cursor / part
        if cursor.exists() and cursor.is_symlink():
            raise SafeEditError(f"symlink path component forbidden: {rel_path}")

    candidate = root / raw
    if candidate.exists() and candidate.is_symlink():
        raise SafeEditError(f"symlink target forbidden: {rel_path}")

    resolved = candidate.resolve(strict=False)
    if resolved != root and root not in resolved.parents:
        raise SafeEditError(f"path escapes repo_root: {rel_path}")
    return candidate


def parse_plan_json(text: str) -> dict[str, Any]:
    """Parse a strict plan from raw JSON or one outer ```json fenced block."""
    if not isinstance(text, str):
        raise SafeEditError("plan must be text")
    if len(text.encode("utf-8")) > MAX_PLAN_BYTES:
        raise SafeEditError("plan exceeds maximum size")
    stripped = text.strip()
    if stripped.startswith("```json") and stripped.endswith("```"):
        stripped = stripped[len("```json"): -3].strip()
    try:
        plan = json.loads(stripped)
    except json.JSONDecodeError as exc:
        raise SafeEditError(f"invalid JSON: {exc}") from exc
    if not isinstance(plan, dict):
        raise SafeEditError("top-level plan must be an object")
    validate_plan_shape(plan)
    return plan


def validate_plan_shape(plan: dict[str, Any]) -> None:
    _strict_keys(plan, {"schema", "files"}, "plan")
    if plan.get("schema") != SCHEMA:
        raise SafeEditError(f"schema must be exactly {SCHEMA}")
    files = plan.get("files")
    if not isinstance(files, list) or not (1 <= len(files) <= MAX_FILES):
        raise SafeEditError(f"files must contain 1..{MAX_FILES} entries")

    seen: set[str] = set()
    for idx, entry in enumerate(files):
        if not isinstance(entry, dict):
            raise SafeEditError(f"files[{idx}] must be an object")
        _strict_keys(entry, {"path", "operation", "base_sha256", "replacements", "content"}, f"files[{idx}]")
        path = entry.get("path")
        if not isinstance(path, str) or not path:
            raise SafeEditError(f"files[{idx}].path must be a non-empty string")
        if path in seen:
            raise SafeEditError(f"duplicate file entry forbidden: {path}")
        seen.add(path)

        op = entry.get("operation")
        if op == "edit":
            base_sha = entry.get("base_sha256")
            if not isinstance(base_sha, str) or len(base_sha) != 64 or any(c not in "0123456789abcdef" for c in base_sha):
                raise SafeEditError(f"files[{idx}].base_sha256 must be lowercase SHA-256 hex")
            replacements = entry.get("replacements")
            if not isinstance(replacements, list) or not (1 <= len(replacements) <= MAX_REPLACEMENTS_PER_FILE):
                raise SafeEditError(
                    f"files[{idx}].replacements must contain 1..{MAX_REPLACEMENTS_PER_FILE} entries"
                )
            if "content" in entry:
                raise SafeEditError(f"files[{idx}]: content is forbidden for edit operations")
            for ridx, repl in enumerate(replacements):
                if not isinstance(repl, dict):
                    raise SafeEditError(f"files[{idx}].replacements[{ridx}] must be an object")
                _strict_keys(repl, {"old_text", "new_text"}, f"files[{idx}].replacements[{ridx}]")
                old = repl.get("old_text")
                new = repl.get("new_text")
                if not isinstance(old, str) or not old:
                    raise SafeEditError(f"files[{idx}].replacements[{ridx}].old_text must be non-empty text")
                if not isinstance(new, str):
                    raise SafeEditError(f"files[{idx}].replacements[{ridx}].new_text must be text")
        elif op == "create":
            if "base_sha256" in entry or "replacements" in entry:
                raise SafeEditError(f"files[{idx}]: create cannot carry base_sha256/replacements")
            if not isinstance(entry.get("content"), str):
                raise SafeEditError(f"files[{idx}].content must be text for create")
        else:
            raise SafeEditError(f"files[{idx}].operation must be edit or create")


def stage_plan(repo_root: Path, plan: dict[str, Any]) -> list[StagedChange]:
    """Validate and deterministically stage every change without writing."""
    validate_plan_shape(plan)
    root = Path(repo_root)
    if not root.is_dir():
        raise SafeEditError(f"repo_root is not a directory: {root}")

    staged: list[StagedChange] = []
    for entry in plan["files"]:
        rel = entry["path"]
        path = _safe_path(root, rel)
        op = entry["operation"]

        if op == "create":
            if path.exists():
                raise SafeEditError(f"create target already exists: {rel}")
            after = entry["content"]
            staged.append(
                StagedChange(
                    relative_path=rel,
                    operation=op,
                    before=None,
                    after=after,
                    before_sha256=None,
                    after_sha256=_sha256_text(after),
                    replaced_chars=0,
                    replaced_fraction=0.0,
                )
            )
            continue

        if not path.is_file():
            raise SafeEditError(f"edit target must be an existing regular file: {rel}")
        try:
            before = path.read_text(encoding="utf-8")
        except UnicodeDecodeError as exc:
            raise SafeEditError(f"edit target is not UTF-8 text: {rel}") from exc
        actual_sha = _sha256_text(before)
        if actual_sha != entry["base_sha256"]:
            raise SafeEditError(
                f"stale base hash for {rel}: expected {entry['base_sha256']}, observed {actual_sha}"
            )

        after = before
        replaced_chars = 0
        for ridx, repl in enumerate(entry["replacements"]):
            old = repl["old_text"]
            count = after.count(old)
            if count != 1:
                raise SafeEditError(
                    f"{rel} replacement[{ridx}] old_text must match exactly once in staged content; observed {count}"
                )
            replaced_chars += len(old)
            after = after.replace(old, repl["new_text"], 1)

        if after == before:
            raise SafeEditError(f"edit is a no-op: {rel}")
        denominator = max(len(before), 1)
        replaced_fraction = replaced_chars / denominator
        if replaced_fraction > MAX_REPLACED_FRACTION:
            raise SafeEditError(
                f"edit span too broad for surgical path: {rel} replaces {replaced_fraction:.3f} of base "
                f"(max {MAX_REPLACED_FRACTION:.3f})"
            )

        staged.append(
            StagedChange(
                relative_path=rel,
                operation=op,
                before=before,
                after=after,
                before_sha256=actual_sha,
                after_sha256=_sha256_text(after),
                replaced_chars=replaced_chars,
                replaced_fraction=replaced_fraction,
            )
        )
    return staged


def _atomic_write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=f".{path.name}.safeedit.", dir=str(path.parent))
    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(temp_path, path)
    except Exception:
        try:
            temp_path.unlink(missing_ok=True)
        finally:
            raise


def apply_plan(repo_root: Path, plan: dict[str, Any]) -> dict[str, Any]:
    """Apply a fully staged plan with best-effort rollback on write failure.

    All semantic/safety checks run before the first write. Each individual
    path update uses same-directory temp + os.replace. If a later path write
    fails, already-written paths are restored from the exact staged snapshot.
    This is transaction-like for ordinary exceptions, but not a claim of
    crash-atomicity across multiple filesystem paths.
    """
    root = Path(repo_root)
    staged = stage_plan(root, plan)
    applied: list[StagedChange] = []
    try:
        for change in staged:
            path = _safe_path(root, change.relative_path)
            _atomic_write_text(path, change.after)
            applied.append(change)
    except Exception as exc:
        rollback_errors: list[str] = []
        for change in reversed(applied):
            path = _safe_path(root, change.relative_path)
            try:
                if change.before is None:
                    path.unlink(missing_ok=True)
                else:
                    _atomic_write_text(path, change.before)
            except Exception as rollback_exc:  # pragma: no cover - catastrophic FS failure path
                rollback_errors.append(f"{change.relative_path}: {rollback_exc}")
        detail = f"apply failed and rollback attempted: {exc}"
        if rollback_errors:
            detail += f"; rollback errors={rollback_errors}"
        raise SafeEditError(detail) from exc

    return {
        "schema": "FRANKENSTEIN_SAFE_EDIT_RECEIPT/v1",
        "files": [
            {
                "path": c.relative_path,
                "operation": c.operation,
                "before_sha256": c.before_sha256,
                "after_sha256": c.after_sha256,
                "before_bytes": None if c.before is None else len(c.before.encode("utf-8")),
                "after_bytes": len(c.after.encode("utf-8")),
                "replaced_chars": c.replaced_chars,
                "replaced_fraction": c.replaced_fraction,
            }
            for c in staged
        ],
    }


def snapshot_for_prompt(repo_root: Path, relative_paths: list[str]) -> list[dict[str, Any]]:
    """Return exact current UTF-8 content + SHA-256 for explicitly named files.

    The caller decides which paths are task-relevant; this helper deliberately
    performs no fuzzy repository scan and no provider interaction.
    """
    root = Path(repo_root)
    if not root.is_dir():
        raise SafeEditError(f"repo_root is not a directory: {root}")
    if len(relative_paths) > MAX_FILES:
        raise SafeEditError(f"at most {MAX_FILES} prompt snapshots are allowed")
    out: list[dict[str, Any]] = []
    seen: set[str] = set()
    for rel in relative_paths:
        if rel in seen:
            raise SafeEditError(f"duplicate snapshot path: {rel}")
        seen.add(rel)
        path = _safe_path(root, rel)
        if not path.is_file():
            raise SafeEditError(f"snapshot target is not an existing regular file: {rel}")
        try:
            content = path.read_text(encoding="utf-8")
        except UnicodeDecodeError as exc:
            raise SafeEditError(f"snapshot target is not UTF-8 text: {rel}") from exc
        out.append({"path": rel, "sha256": _sha256_text(content), "content": content})
    return out
