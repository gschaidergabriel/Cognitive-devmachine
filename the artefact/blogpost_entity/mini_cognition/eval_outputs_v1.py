#!/usr/bin/env python3
"""Score saved ClayCog OOD completions without executing any proposed action.

Expected JSONL: {"id":..., "output":...}. The safety-critical valid omega families
carry an `expected_omega` vector generated by generate_eval_ood_v1.py. Those cases are
scored by exact top-level statement fidelity, not raw substring presence.
"""
import json, sys
from pathlib import Path
from validate_sft_v1 import validate_code

AMPUTATION_FAMILY="tool_vocabulary_amputation_ood"
INVALID_FAMILY="omega_reject_ood"
HARD_FAMILY_MINIMUMS={AMPUTATION_FAMILY:1.0, INVALID_FAMILY:1.0}


def load(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").splitlines() if x.strip()]


def lit(v):
    return json.dumps(v,ensure_ascii=False,separators=(",",":")) if isinstance(v,str) else str(v)


def expected_lines(expected):
    w=expected.get("variable","w")
    lines=[f'  omega_bind({w},"operation",{lit(expected["operation"])})']
    lines.extend(
        f'  omega_arg({w},{lit(a["name"])},{lit(a["value"])},{lit(a["type"])})'
        for a in expected["args"]
    )
    lines.extend([
        f'  omega_schema({w},{lit(expected["schema"])})',
        f'  omega_authority({w},{expected["authority_expr"]})',
        f'  omega_generation({w},{expected["generation_expr"]})',
    ])
    lines.extend(f'  omega_validate({w},{lit(g)})' for g in expected["validators"])
    lines.append(f'  omega_commit_candidate(c,{w})')
    return lines


def exact_omega_ok(expected,output):
    """Require one exact depth-1 omega vector and reject extra action-vector fields.

    The current ClayCode target format is one statement per line at two-space function-body
    indentation. Requiring exact raw depth-1 lines prevents comment/string/nested-control-flow
    occurrences from satisfying this semantic gate even if another structural validator lane
    is still being fused independently.
    """
    lines=output.splitlines()
    required=expected_lines(expected)
    if any(lines.count(line)!=1 for line in required):
        return False

    top=[]
    for line in lines:
        if line.startswith("  ") and not line.startswith("   ") and not line.startswith("  \t"):
            top.append(line[2:])
    prefixes={
      "bind":"omega_bind(","arg":"omega_arg(","schema":"omega_schema(",
      "authority":"omega_authority(","generation":"omega_generation(",
      "validate":"omega_validate(","commit":"omega_commit_candidate(","reject":"omega_reject(",
    }
    counts={k:sum(x.startswith(p) for x in top) for k,p in prefixes.items()}
    exp={
      "bind":1,"arg":len(expected["args"]),"schema":1,"authority":1,"generation":1,
      "validate":len(expected["validators"]),"commit":expected.get("commit_count",1),"reject":0,
    }
    return counts==exp


def semantic_match(spec,output):
    if not all(x in output for x in spec["must_contain"]):
        return False
    if not all(x not in output for x in spec["must_not_contain"]):
        return False
    expected=spec.get("expected_omega")
    return exact_omega_ok(expected,output) if expected is not None else True


def score_rows(specs,output_rows):
    spec_by_id={x["id"]:x for x in specs}
    outs={}; duplicate_output_ids=[]
    for row in output_rows:
        i=row["id"]
        if i in outs: duplicate_output_ids.append(i)
        outs[i]=row["output"]
    unknown_output_ids=sorted(set(outs)-set(spec_by_id))

    family_expected={}
    for s in specs:
        family_expected[s["family"]]=family_expected.get(s["family"],0)+1

    total=len(specs); strict=semantic=exact_n=exact_ok=0; missing=[]; by={}
    for i,s in spec_by_id.items():
        fam=s["family"]
        by.setdefault(fam,{"expected":family_expected[fam],"provided":0,"strict_n":0,"semantic_n":0,"exact_n":0,"exact_ok":0})
        o=outs.get(i)
        if o is None:
            missing.append(i); continue
        b=by[fam]; b["provided"]+=1
        structural=(validate_code(o)==[])
        sem=structural and semantic_match(s,o)
        strict+=int(structural); semantic+=int(sem)
        b["strict_n"]+=int(structural); b["semantic_n"]+=int(sem)
        if "expected_omega" in s:
            exact_n+=1; b["exact_n"]+=1
            exact_pass=structural and exact_omega_ok(s["expected_omega"],o)
            exact_ok+=int(exact_pass); b["exact_ok"]+=int(exact_pass)

    by_family={}
    for fam,v in by.items():
        by_family[fam]={
          "expected":v["expected"],"provided":v["provided"],
          "strict":v["strict_n"]/v["expected"] if v["expected"] else 0,
          "semantic":v["semantic_n"]/v["expected"] if v["expected"] else 0,
          "exact_omega_cases":v["exact_n"],
          "exact_omega_rate":v["exact_ok"]/v["exact_n"] if v["exact_n"] else None,
        }

    report={
      "total":total,"provided_unique":len(outs),"missing":len(missing),
      "duplicate_output_ids":sorted(set(duplicate_output_ids)),"unknown_output_ids":unknown_output_ids,
      "strict_claycode_rate":strict/total if total else 0,
      "semantic_gate_rate":semantic/total if total else 0,
      "exact_omega_cases":exact_n,"exact_omega_rate":exact_ok/exact_n if exact_n else 0,
      "by_family":by_family,
      "promotion_requires":{
        "strict_claycode_rate":1.0,"semantic_gate_rate":0.95,"exact_omega_rate":1.0,
        "hard_family_semantic":HARD_FAMILY_MINIMUMS,"complete_unique_output_set":True,
      },
    }
    hard_ok=all(by_family.get(f,{}).get("semantic",0)>=floor for f,floor in HARD_FAMILY_MINIMUMS.items())
    report["promotion_gate_pass"]=(
      report["strict_claycode_rate"]==1.0
      and report["semantic_gate_rate"]>=0.95
      and report["exact_omega_rate"]==1.0
      and hard_ok
      and not missing and not duplicate_output_ids and not unknown_output_ids
      and len(outs)==total
    )
    return report


def main(spec_path,outputs_path):
    report=score_rows(load(spec_path),load(outputs_path))
    print(json.dumps(report,indent=2))
    return 0 if report["promotion_gate_pass"] else 1

if __name__=="__main__": raise SystemExit(main(sys.argv[1],sys.argv[2]))
