from __future__ import annotations

import hashlib
import json
import os
import subprocess
import time
from pathlib import Path
from typing import Any

SCHEMA_VERSION = "1.0"


def _state_dir() -> Path:
    p = Path(os.getenv("CLAY_MCP_STATE_DIR", "/var/lib/clay-vps-mcp"))
    p.mkdir(parents=True, exist_ok=True)
    return p


def _history_repo() -> Path:
    return Path(os.getenv("CLAY_HISTORY_REPO", "/srv/clay-history")).resolve(strict=False)


def _roots() -> list[Path]:
    raw = os.getenv("CLAY_MCP_ALLOWED_ROOTS", "/srv/clay-mcp/workspace,/srv/models,/opt/frank,/opt/clay")
    return [Path(x.strip()).resolve(strict=False) for x in raw.split(",") if x.strip()]


def _inside_allowed(path: Path) -> bool:
    p = path.resolve(strict=False)
    for root in _roots():
        try:
            p.relative_to(root)
            return True
        except ValueError:
            continue
    return False


def _git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", str(repo), *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        errors="replace",
        timeout=60,
        check=check,
    )


def ensure_repo() -> Path:
    repo = _history_repo()
    repo.mkdir(parents=True, exist_ok=True)
    if not (repo / ".git").exists():
        cp = subprocess.run(["git", "init", "-b", "main", str(repo)], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=False)
        if cp.returncode != 0:
            subprocess.run(["git", "init", str(repo)], check=True)
    _git(repo, "config", "user.name", "clay-vps-history")
    _git(repo, "config", "user.email", "clay-vps-history@localhost")
    (repo / "events").mkdir(exist_ok=True)
    (repo / "processes").mkdir(exist_ok=True)
    readme = repo / "README.md"
    if not readme.exists():
        readme.write_text(
            "# Clay VPS Build History\n\nAppend-only local Git ledger generated by clay-vps-mcp. "
            "Large artifacts are referenced by content hash rather than copied into Git. Secrets are excluded.\n",
            encoding="utf-8",
        )
        _git(repo, "add", "README.md")
        _git(repo, "commit", "-m", "history: initialize Clay VPS build ledger", check=False)
    return repo


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(4 * 1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _file_meta(path: Path) -> dict[str, Any]:
    st = path.stat()
    return {
        "path": str(path.resolve()),
        "size": st.st_size,
        "mtime": st.st_mtime,
        "sha256": _sha256(path),
    }


def _git_state(cwd: Path) -> dict[str, Any] | None:
    if not cwd.exists() or not cwd.is_dir():
        return None
    probe = subprocess.run(["git", "-C", str(cwd), "rev-parse", "--show-toplevel"], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=10, check=False)
    if probe.returncode != 0:
        return None
    repo = Path(probe.stdout.strip())
    head = _git(repo, "rev-parse", "HEAD", check=False).stdout.strip()
    branch = _git(repo, "branch", "--show-current", check=False).stdout.strip()
    status = _git(repo, "status", "--porcelain=v1", check=False).stdout
    diff = _git(repo, "diff", "--binary", check=False).stdout.encode("utf-8", errors="replace")
    staged = _git(repo, "diff", "--cached", "--binary", check=False).stdout.encode("utf-8", errors="replace")
    return {
        "repo_root": str(repo.resolve()),
        "head": head or None,
        "branch": branch or None,
        "dirty": bool(status.strip()),
        "status_porcelain": status[:200_000],
        "working_diff_sha256": hashlib.sha256(diff).hexdigest(),
        "staged_diff_sha256": hashlib.sha256(staged).hexdigest(),
    }


def _candidate_paths(event: dict[str, Any]) -> list[Path]:
    values: list[str] = []
    payload = event.get("payload") or {}
    result = event.get("result") or {}
    for obj in (payload, result):
        for key in ("path", "backup", "log", "cwd"):
            value = obj.get(key)
            if isinstance(value, str):
                values.append(value)
        argv = obj.get("argv")
        if isinstance(argv, list):
            values.extend(x for x in argv[1:] if isinstance(x, str))
    cwd_raw = payload.get("cwd") if isinstance(payload.get("cwd"), str) else None
    cwd = Path(cwd_raw) if cwd_raw else None
    out: list[Path] = []
    seen: set[str] = set()
    for raw in values:
        if not raw or raw.startswith("-") or "\x00" in raw:
            continue
        p = Path(raw).expanduser()
        if not p.is_absolute() and cwd:
            p = cwd / p
        try:
            p = p.resolve(strict=True)
        except Exception:
            continue
        if not p.is_file() or not _inside_allowed(p):
            continue
        key = str(p)
        if key not in seen:
            seen.add(key)
            out.append(p)
    return out[:64]


def _process_record(process_id: str) -> dict[str, Any] | None:
    path = _state_dir() / "processes.json"
    try:
        reg = json.loads(path.read_text(encoding="utf-8"))
        rec = reg.get(process_id)
        return rec if isinstance(rec, dict) else None
    except Exception:
        return None


def enrich(event: dict[str, Any]) -> dict[str, Any]:
    canonical = json.dumps(event, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    event_id = hashlib.sha256(canonical).hexdigest()
    payload = event.get("payload") or {}
    cwd_raw = payload.get("cwd") if isinstance(payload.get("cwd"), str) else None
    cwd = Path(cwd_raw).resolve(strict=False) if cwd_raw else None
    files = []
    for p in _candidate_paths(event):
        try:
            files.append(_file_meta(p))
        except Exception as exc:
            files.append({"path": str(p), "hash_error": str(exc)})
    process_id = (event.get("result") or {}).get("process_id")
    process = _process_record(process_id) if isinstance(process_id, str) else None
    return {
        "history_schema_version": SCHEMA_VERSION,
        "event_id": event_id,
        "recorded_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "source_event": event,
        "source_git": _git_state(cwd) if cwd else None,
        "referenced_files": files,
        "owned_process": process,
        "secret_policy": "secret values intentionally excluded; only source audit fields are persisted",
    }


def commit_event(event: dict[str, Any]) -> str:
    repo = ensure_repo()
    enriched = enrich(event)
    event_id = enriched["event_id"]
    existing = list((repo / "events").rglob(f"*{event_id[:16]}*.json"))
    if existing:
        return event_id
    iso = str((event.get("time") or time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()))).replace(":", "").replace("-", "")
    day = time.strftime("%Y/%m/%d", time.gmtime(float(event.get("epoch", time.time()))))
    directory = repo / "events" / day
    directory.mkdir(parents=True, exist_ok=True)
    rel = Path("events") / day / f"{iso}-{event_id[:16]}.json"
    (repo / rel).write_text(json.dumps(enriched, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    _git(repo, "add", str(rel))
    action = str(event.get("action", "event"))[:60]
    cp = _git(repo, "commit", "-m", f"event: {action} {event_id[:12]}", check=False)
    if cp.returncode not in (0, 1):
        raise RuntimeError(cp.stderr)
    return event_id


def mirror_once() -> int:
    audit = _state_dir() / "audit.jsonl"
    if not audit.exists():
        return 0
    cursor_path = _state_dir() / "history.cursor"
    try:
        offset = int(cursor_path.read_text(encoding="utf-8").strip() or "0")
    except Exception:
        offset = 0
    count = 0
    with audit.open("rb") as f:
        size = audit.stat().st_size
        if offset > size:
            offset = 0
        f.seek(offset)
        while True:
            start = f.tell()
            line = f.readline()
            if not line:
                break
            if not line.endswith(b"\n"):
                f.seek(start)
                break
            try:
                event = json.loads(line.decode("utf-8"))
                commit_event(event)
            except Exception as exc:
                error_event = {
                    "time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "epoch": time.time(),
                    "action": "history_mirror_error",
                    "payload": {"audit_offset": start},
                    "result": {"error": str(exc)},
                }
                try:
                    commit_event(error_event)
                except Exception:
                    pass
            offset = f.tell()
            cursor_path.write_text(str(offset), encoding="utf-8")
            count += 1
    return count


def main() -> None:
    ensure_repo()
    sleep_s = max(0.2, float(os.getenv("CLAY_HISTORY_POLL_SECONDS", "1.0")))
    while True:
        mirror_once()
        time.sleep(sleep_s)


if __name__ == "__main__":
    main()
