#!/usr/bin/env python3
"""Score saved model completions without executing any proposed action.
Expected JSONL: {"id":..., "output":...}. OOD spec generated by generate_eval_ood_v1.py.
"""
import json, sys
from collections import Counter
from pathlib import Path
from validate_sft_v1 import validate_code

def load(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").splitlines() if x.strip()]

def load_unique(rows,key,label):
    out={}; dup=[]
    for row in rows:
        k=row[key]
        if k in out: dup.append(k)
        else: out[k]=row
    if dup: raise ValueError(f"duplicate {label} id(s): {sorted(set(dup))[:10]}")
    return out

def semantic_errors(spec,output):
    if not isinstance(output,str): return ["output_not_string"]
    lines=[x.strip() for x in output.splitlines() if x.strip()]
    counts=Counter(lines); errors=[]
    for expected in spec.get("required_lines_once",[]):
        n=counts[expected]
        if n!=1: errors.append(f"required_line_count:{expected}:{n}")
    for prefix in spec.get("required_prefixes_once",[]):
        n=sum(1 for line in lines if line.startswith(prefix))
        if n!=1: errors.append(f"required_prefix_count:{prefix}:{n}")
    for forbidden in spec.get("forbidden_lines",[]):
        if counts[forbidden]: errors.append(f"forbidden_line:{forbidden}")
    for prefix in spec.get("forbidden_prefixes",[]):
        if any(line.startswith(prefix) for line in lines): errors.append(f"forbidden_prefix:{prefix}")
    for x in spec.get("must_contain",[]):
        if x not in output: errors.append("missing_legacy:"+x)
    for x in spec.get("must_not_contain",[]):
        if x in output: errors.append("forbidden_legacy:"+x)
    return errors

def score_case(spec,output):
    structural=(isinstance(output,str) and validate_code(output)==[])
    sem_errors=semantic_errors(spec,output) if structural else ["structural_invalid"]
    return structural, structural and not sem_errors, sem_errors

def main(spec_path, outputs_path):
    try:
        specs=load_unique(load(spec_path),"id","spec")
        output_rows=load(outputs_path)
        outs=load_unique(output_rows,"id","output")
    except (KeyError,TypeError,ValueError,json.JSONDecodeError) as exc:
        print(json.dumps({"error":"invalid_eval_input","detail":str(exc)},indent=2)); return 2
    expected=set(specs); supplied=set(outs)
    missing=sorted(expected-supplied); unexpected=sorted(supplied-expected)
    strict=semantic=0; by={}; failures=[]
    for i,s in specs.items():
        o=outs.get(i)
        if o is None: continue
        structural,semantic_ok,sem_errors=score_case(s,o)
        strict+=int(structural); semantic+=int(semantic_ok)
        fam=s["family"]; by.setdefault(fam,[0,0,0]); by[fam][0]+=1; by[fam][1]+=int(structural); by[fam][2]+=int(semantic_ok)
        if not semantic_ok and len(failures)<20:
            failures.append({"id":i,"family":fam,"structural":structural,"semantic_errors":sem_errors[:8]})
    total=len(specs)
    report={
      "semantic_contract":"claycog-ood-semantic/v2",
      "total":total,"provided_expected":len(expected & supplied),"missing":len(missing),"unexpected":len(unexpected),
      "strict_claycode_rate":strict/total if total else 0,
      "semantic_gate_rate":semantic/total if total else 0,
      "by_family":{k:{"n":v[0],"strict":v[1]/v[0],"semantic":v[2]/v[0]} for k,v in by.items()},
      "promotion_requires":{"strict_claycode_rate":1.0,"semantic_gate_rate":0.95,"missing":0,"unexpected":0},
      "sample_failures":failures,
    }
    print(json.dumps(report,indent=2))
    return 0 if report["strict_claycode_rate"]==1 and report["semantic_gate_rate"]>=.95 and not missing and not unexpected else 1

if __name__=="__main__": raise SystemExit(main(sys.argv[1],sys.argv[2]))
