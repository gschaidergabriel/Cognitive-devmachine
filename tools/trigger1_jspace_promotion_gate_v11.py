#!/usr/bin/env python3
"""Abstract-state + scope-matched successor promotion gate for Trigger-1 J-Space.

v11 composes v10 and closes the three remaining blockers for a stronger claim:
1. exact frozen abstract-state prompts are label-free and payload-lexically disjoint across
   BASIS/CALIBRATION/HOLDOUT, with obvious yes/no/approval/compliance words absent;
2. CALIBRATION and HOLDOUT are exact 3x3 semantic-metadata x arbitrary-output-code
   factorials generated by the frozen protocol; and
3. the historical last-token PyTorch witness is excluded. Promotion instead requires
   matched control evidence for an all-token layer-output PyTorch broadcast and native
   pinned llama.cpp cvec on the exact frozen HOLDOUT cases.

This gate deliberately checks causal operator/scope parity plus replicated directional
control signatures, not exact numerical equality between FP32 PyTorch and Q8 GGUF.
It remains adjudication-only and non-minting; executable receipt authenticity and final
promotion remain external evidence/review responsibilities.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Any

from tools import trigger1_abstract_state_protocol_v1 as abstract_protocol
from tools import trigger1_jspace_promotion_gate_v10 as v10
from tools import trigger1_scope_matched_broadcast_witness as scope_witness
from tools import trigger1_v7_factorial_case_evidence as producer

VERDICT_SCHEMA = "CLAY_TRIGGER1_JSPACE_PROMOTION_GATE/v11"
BATCH_SCHEMA = "CLAY_TRIGGER1_JSPACE_BATCH_PROMOTION_SCAN/v11"
SCOPE_EVIDENCE_SCHEMA = "CLAY_TRIGGER1_SCOPE_MATCHED_BACKEND_REPLICATION/v1"
BACKENDS = ("PYTORCH_ALL_TOKEN_BROADCAST", "NATIVE_LLAMA_CPP_CVEC")
REQUIRED_CONTROLS = tuple(producer.CONTROLS)
NULL_TOLERANCE = 1e-5


def _sha256(value: Any) -> bool:
    if not isinstance(value, str) or len(value) != 64:
        return False
    try:
        int(value, 16)
    except ValueError:
        return False
    return value == value.lower()


def _protocol_binding(candidate: dict[str, Any]) -> dict[str, Any]:
    failures: list[str] = []
    expected = abstract_protocol.validate_design()
    if expected.get("pass") is not True:
        failures.append("INTERNAL_ABSTRACT_PROTOCOL_DESIGN_MUST_PASS")

    declared = candidate.get("abstract_state_protocol")
    if not isinstance(declared, dict):
        failures.append("ABSTRACT_STATE_PROTOCOL_ATTESTATION_REQUIRED")
        declared = {}
    for field in (
        "protocol_sha256",
        "basis_design_sha256",
        "case_plan_sha256",
        "payload_lexicon_sha256",
        "payload_lexicon_pairwise_disjoint",
        "canonical_status_words_model_facing_absent",
        "semantic_x_output_code_counterbalanced",
        "generic_instruction_scaffold_common_mode",
        "explicit_yes_no_approval_compliance_vocabulary_absent",
    ):
        if declared.get(field) != expected.get(field):
            failures.append(f"ABSTRACT_STATE_PROTOCOL_FIELD_MISMATCH:{field}")

    evidence = candidate.get("preregistration_evidence")
    case_plans = evidence.get("case_plans") if isinstance(evidence, dict) else None
    if not isinstance(case_plans, dict):
        failures.append("ABSTRACT_STATE_BOUND_SOURCE_CASE_PLANS_REQUIRED")
        case_plans = {}
    expected_plans = abstract_protocol.expected_case_plans()
    for split in ("CALIBRATION", "HOLDOUT"):
        source_plan = case_plans.get(split)
        if not isinstance(source_plan, dict):
            failures.append(f"ABSTRACT_STATE_{split}_SOURCE_PLAN_REQUIRED")
            continue
        if source_plan.get("plan_sha256") != expected_plans[split].get("plan_sha256"):
            failures.append(f"ABSTRACT_STATE_{split}_PLAN_SHA256_MISMATCH")
        if source_plan != expected_plans[split]:
            failures.append(f"ABSTRACT_STATE_{split}_PLAN_OBJECT_MISMATCH")

    return {
        "pass": not failures,
        "failures": sorted(set(failures)),
        "protocol_sha256": expected.get("protocol_sha256"),
        "case_plan_sha256": expected.get("case_plan_sha256"),
    }


def _target_score_map(rows: list[dict[str, Any]], prefix: str, failures: list[str]) -> dict[str, float]:
    scores: dict[str, float] = {}
    for index, row in enumerate(rows):
        control = row.get("control")
        if control not in REQUIRED_CONTROLS:
            failures.append(f"{prefix}_ROW_{index}_CONTROL_INVALID")
            continue
        if control in scores:
            failures.append(f"{prefix}_DUPLICATE_CONTROL:{control}")
            continue
        value = row.get("target_score")
        if not isinstance(value, (int, float)) or isinstance(value, bool) or not math.isfinite(float(value)):
            failures.append(f"{prefix}_ROW_{index}_TARGET_SCORE_FINITE_REQUIRED")
            continue
        scores[str(control)] = float(value)
    if set(scores) != set(REQUIRED_CONTROLS):
        failures.append(f"{prefix}_EXACT_SIX_CONTROLS_REQUIRED")
    return scores


def _case_signature(scores: dict[str, float]) -> dict[str, float] | None:
    if set(scores) != set(REQUIRED_CONTROLS):
        return None
    return {
        "plus_vs_baseline": scores["+VECTOR"] - scores["BASELINE"],
        "baseline_vs_sign_flip": scores["BASELINE"] - scores["SIGN_FLIP"],
        "null_drift": abs(scores["NULL_VECTOR"] - scores["BASELINE"]),
        "plus_vs_orthogonal": scores["+VECTOR"] - scores["ORTHOGONAL_SAME_NORM"],
        "plus_vs_permuted": scores["+VECTOR"] - scores["PERMUTED_SAME_NORM"],
    }


def _signature_pass(sig: dict[str, float] | None) -> bool:
    return bool(
        sig is not None
        and sig["plus_vs_baseline"] > 0.0
        and sig["baseline_vs_sign_flip"] > 0.0
        and sig["null_drift"] <= NULL_TOLERANCE
        and sig["plus_vs_orthogonal"] > 0.0
        and sig["plus_vs_permuted"] > 0.0
    )


def _scope_replication(candidate: dict[str, Any]) -> dict[str, Any]:
    failures: list[str] = []
    evidence = candidate.get("scope_matched_replication")
    if not isinstance(evidence, dict):
        return {"pass": False, "failures": ["SCOPE_MATCHED_REPLICATION_EVIDENCE_REQUIRED"]}
    if evidence.get("schema") != SCOPE_EVIDENCE_SCHEMA:
        failures.append("SCOPE_MATCHED_REPLICATION_SCHEMA_INVALID")

    contract = scope_witness.scope_contract()
    if evidence.get("scope_contract_sha256") != contract["scope_contract_sha256"]:
        failures.append("SCOPE_CONTRACT_SHA256_MISMATCH")
    if evidence.get("llama_cpp_commit") != scope_witness.PINNED_LLAMA_CPP_COMMIT:
        failures.append("SCOPE_PINNED_LLAMA_CPP_COMMIT_MISMATCH")
    if evidence.get("injection_layer") != scope_witness.INJECTION_LAYER:
        failures.append("SCOPE_INJECTION_LAYER_MISMATCH")
    if evidence.get("dimension") != scope_witness.N_EMBD:
        failures.append("SCOPE_HIDDEN_DIMENSION_MISMATCH")
    if evidence.get("historical_last_token_witness_used_for_promotion") is not False:
        failures.append("HISTORICAL_LAST_TOKEN_WITNESS_MUST_BE_EXCLUDED")
    basis_packet_sha = evidence.get("basis_packet_sha256")
    if not _sha256(basis_packet_sha):
        failures.append("SCOPE_BASIS_PACKET_SHA256_REQUIRED")

    rows = evidence.get("rows")
    if not isinstance(rows, list) or not rows:
        failures.append("SCOPE_MATCHED_RUNTIME_ROWS_REQUIRED")
        rows = []

    expected_holdout = abstract_protocol.expected_case_plans()["HOLDOUT"]
    expected_cases = {row["case_id"]: row for row in expected_holdout["cases"]}
    grouped: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for index, row in enumerate(rows):
        if not isinstance(row, dict):
            failures.append(f"SCOPE_ROW_{index}_OBJECT_REQUIRED")
            continue
        backend = row.get("backend")
        case_id = row.get("case_id")
        control = row.get("control")
        if backend not in BACKENDS:
            failures.append(f"SCOPE_ROW_{index}_BACKEND_INVALID")
            continue
        if case_id not in expected_cases:
            failures.append(f"SCOPE_ROW_{index}_CASE_NOT_IN_FROZEN_HOLDOUT")
            continue
        expected_case = expected_cases[str(case_id)]
        if row.get("prompt_sha256") != expected_case.get("prompt_sha256"):
            failures.append(f"SCOPE_ROW_{index}_PROMPT_SHA256_MISMATCH")
        if row.get("semantic_target") != expected_case.get("semantic_target"):
            failures.append(f"SCOPE_ROW_{index}_SEMANTIC_METADATA_MISMATCH")
        if row.get("output_code_identity") != expected_case.get("output_code_identity"):
            failures.append(f"SCOPE_ROW_{index}_OUTPUT_CODE_IDENTITY_MISMATCH")
        if row.get("basis_packet_sha256") != basis_packet_sha:
            failures.append(f"SCOPE_ROW_{index}_BASIS_PACKET_MISMATCH")
        if not _sha256(row.get("runtime_receipt_sha256")):
            failures.append(f"SCOPE_ROW_{index}_RUNTIME_RECEIPT_SHA256_REQUIRED")
        expected_scope = (
            scope_witness.PYTORCH_SCOPE
            if backend == "PYTORCH_ALL_TOKEN_BROADCAST"
            else scope_witness.NATIVE_SCOPE
        )
        if control != "BASELINE" and row.get("intervention_scope") != expected_scope:
            failures.append(f"SCOPE_ROW_{index}_INTERVENTION_SCOPE_MISMATCH")
        if control == "BASELINE" and row.get("intervention_scope") not in ("BASELINE_NO_VECTOR", expected_scope):
            failures.append(f"SCOPE_ROW_{index}_BASELINE_SCOPE_INVALID")
        grouped.setdefault((str(backend), str(case_id)), []).append(row)

    expected_group_keys = {(backend, case_id) for backend in BACKENDS for case_id in expected_cases}
    if set(grouped) != expected_group_keys:
        failures.append("SCOPE_BACKEND_CASE_UNIVERSE_MISMATCH")

    signatures: dict[str, dict[str, dict[str, float]]] = {backend: {} for backend in BACKENDS}
    for backend, case_id in sorted(expected_group_keys):
        case_rows = grouped.get((backend, case_id), [])
        score_map = _target_score_map(case_rows, f"SCOPE_{backend}_{case_id}", failures)
        sig = _case_signature(score_map)
        if sig is not None:
            signatures[backend][case_id] = sig
        if not _signature_pass(sig):
            failures.append(f"SCOPE_CAUSAL_SIGNATURE_FAIL:{backend}:{case_id}")

    agreement_count = 0
    for case_id in expected_cases:
        left = signatures[BACKENDS[0]].get(case_id)
        right = signatures[BACKENDS[1]].get(case_id)
        if _signature_pass(left) and _signature_pass(right):
            agreement_count += 1
    if agreement_count != len(expected_cases):
        failures.append("SCOPE_CROSS_BACKEND_DIRECTIONAL_AGREEMENT_INCOMPLETE")

    expected_rows = len(BACKENDS) * len(expected_cases) * len(REQUIRED_CONTROLS)
    if len(rows) != expected_rows:
        failures.append(f"SCOPE_EXACT_RUNTIME_ROW_COUNT_REQUIRED:{expected_rows}")

    return {
        "pass": not failures,
        "failures": sorted(set(failures)),
        "scope_contract_sha256": contract["scope_contract_sha256"],
        "holdout_case_count": len(expected_cases),
        "runtime_row_count": len(rows),
        "cross_backend_directional_agreement_cases": agreement_count,
        "basis_packet_sha256": basis_packet_sha,
        "operator_scope_parity": not any("INTERVENTION_SCOPE_MISMATCH" in x for x in failures),
        "exact_numerical_backend_identity_claimed": False,
    }


def adjudicate(candidate: dict[str, Any]) -> dict[str, Any]:
    base = v10.adjudicate(candidate)
    protocol = _protocol_binding(candidate)
    scope = _scope_replication(candidate)
    hard_ok = protocol.get("pass") is True and scope.get("pass") is True
    scientific = bool(base.get("scientifically_independent_vector_candidate") is True and hard_ok)
    owner = bool(base.get("owner_trigger1_goal_credit_candidate") is True and hard_ok)
    modular = bool(base.get("modular_hcu_jspace_control_candidate") is True and hard_ok)
    failures = sorted(set(list(base.get("v10_failures", [])) + protocol["failures"] + scope["failures"]))
    return {
        **base,
        "schema": VERDICT_SCHEMA,
        "abstract_state_protocol_pass": protocol.get("pass") is True,
        "abstract_state_protocol_sha256": protocol.get("protocol_sha256"),
        "abstract_state_protocol_failures": protocol.get("failures", []),
        "scope_matched_broadcast_native_replication_pass": scope.get("pass") is True,
        "scope_matched_replication_failures": scope.get("failures", []),
        "scope_contract_sha256": scope.get("scope_contract_sha256"),
        "cross_backend_directional_agreement_cases": scope.get("cross_backend_directional_agreement_cases", 0),
        "scientifically_independent_vector_candidate": scientific,
        "owner_trigger1_goal_credit_candidate": owner,
        "owner_trigger1_direct_free_api_model_credit_candidate": owner,
        "modular_hcu_jspace_control_candidate": modular,
        "semantic_jspace_claim_candidate": scientific,
        "abstract_state_control_candidate": scientific,
        "v11_failures": failures,
        "canonical_credit_minted": False,
        "canonical_semantics_promotion": False,
        "whole_entityos_hcu_credit": False,
        "whole_hcu_credit": False,
        "jspace_model_runtime_credit": False,
        "training_credit": False,
        "evidence_boundary": (
            "v11 can nominate a semantic-J-Space/abstract-state candidate only when v10 is green, the exact "
            "frozen label-free payload-lexically-disjoint counterbalanced protocol is the executed producer-plan "
            "universe, and both a PyTorch all-token broadcast and native pinned llama.cpp cvec reproduce the "
            "six-control directional signature on all nine frozen holdout cases. The old last-token witness is "
            "ineligible. Backend magnitudes need not match and this adjudicator does not authenticate external "
            "receipt bytes or mint canonical semantics/runtime/HCU/EntityOS/training credit."
        ),
    }


def adjudicate_file(path: Path) -> dict[str, Any]:
    try:
        candidate = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return {
            "schema": VERDICT_SCHEMA,
            "semantic_jspace_claim_candidate": False,
            "abstract_state_control_candidate": False,
            "canonical_credit_minted": False,
            "v11_failures": [f"CANDIDATE_FILE_INVALID:{type(exc).__name__}"],
        }
    if not isinstance(candidate, dict):
        return {
            "schema": VERDICT_SCHEMA,
            "semantic_jspace_claim_candidate": False,
            "abstract_state_control_candidate": False,
            "canonical_credit_minted": False,
            "v11_failures": ["CANDIDATE_OBJECT_REQUIRED"],
        }
    result = adjudicate(candidate)
    result["candidate_path"] = str(path)
    result["candidate_sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    return result


def scan_batch(batch_dir: Path) -> dict[str, Any]:
    paths = sorted(batch_dir.glob("**/trigger1_direct_steering_candidate.json"))
    verdicts = [adjudicate_file(path) for path in paths]
    positives = [row for row in verdicts if row.get("semantic_jspace_claim_candidate") is True]
    return {
        "schema": BATCH_SCHEMA,
        "candidate_files_seen": len(paths),
        "semantic_jspace_claim_candidates": len(positives),
        "abstract_state_control_candidate": bool(positives),
        "canonical_credit_minted": False,
        "verdicts": verdicts,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--candidate")
    group.add_argument("--batch-dir")
    args = parser.parse_args()
    result = adjudicate_file(Path(args.candidate)) if args.candidate else scan_batch(Path(args.batch_dir))
    print(json.dumps(result, sort_keys=True, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
