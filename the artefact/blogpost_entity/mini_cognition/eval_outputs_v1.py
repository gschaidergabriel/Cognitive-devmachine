#!/usr/bin/env python3
"""Score saved model completions without executing any proposed action.
Expected JSONL: {"id":..., "output":...}. OOD spec generated by generate_eval_ood_v1.py.
"""
import json, sys
from pathlib import Path
from validate_sft_v1 import validate_code

AMPUTATION_FAMILY="tool_vocabulary_amputation_ood"
AMPUTATION_SEMANTIC_MIN=1.0

def load(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").splitlines() if x.strip()]

def main(spec_path, outputs_path):
    specs={x["id"]:x for x in load(spec_path)}
    outs={x["id"]:x["output"] for x in load(outputs_path)}
    family_expected={}
    for s in specs.values(): family_expected[s["family"]]=family_expected.get(s["family"],0)+1
    total=len(specs); strict=semantic=0; missing=[]; by={}
    for i,s in specs.items():
        fam=s["family"]
        by.setdefault(fam,[family_expected[fam],0,0,0])
        o=outs.get(i)
        if o is None:
            missing.append(i); continue
        structural=(validate_code(o)==[])
        semantic_ok=all(x in o for x in s["must_contain"]) and all(x not in o for x in s["must_not_contain"])
        strict+=int(structural); semantic+=int(structural and semantic_ok)
        by[fam][1]+=1; by[fam][2]+=int(structural); by[fam][3]+=int(structural and semantic_ok)
    by_family={
      k:{"expected":v[0],"provided":v[1],"strict":v[2]/v[0] if v[0] else 0,"semantic":v[3]/v[0] if v[0] else 0}
      for k,v in by.items()
    }
    amp=by_family.get(AMPUTATION_FAMILY,{"expected":0,"provided":0,"strict":0,"semantic":0})
    report={
      "total":total,"provided":len(outs),"missing":len(missing),
      "strict_claycode_rate":strict/total if total else 0,
      "semantic_gate_rate":semantic/total if total else 0,
      "by_family":by_family,
      "promotion_requires":{
        "strict_claycode_rate":1.0,
        "semantic_gate_rate":0.95,
        "family_semantic_min":{AMPUTATION_FAMILY:AMPUTATION_SEMANTIC_MIN},
      },
      "promotion_gate":{
        "amputation_family_present":amp["expected"]>0,
        "amputation_semantic_rate":amp["semantic"],
        "amputation_pass":amp["expected"]>0 and amp["semantic"]>=AMPUTATION_SEMANTIC_MIN,
      },
    }
    print(json.dumps(report,indent=2))
    promoted=(
      report["strict_claycode_rate"]==1
      and report["semantic_gate_rate"]>=.95
      and not missing
      and report["promotion_gate"]["amputation_pass"]
    )
    return 0 if promoted else 1

if __name__=="__main__": raise SystemExit(main(sys.argv[1],sys.argv[2]))
