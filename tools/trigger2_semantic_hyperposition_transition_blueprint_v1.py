#!/usr/bin/env python3
"""Trigger-2 semantic-Hyperposition transition blueprint v1.

Builds deterministic, fully crossed candidate/source rows for A/B/C/D/E training
inside the Hyperposition operating frame. State transitions, resolution, discriminator
ordering and salience ordering are generated by the canonical v1 reference labelers and
revalidated by the transition gate.

Rows are deliberately NON-TRAINABLE until exact accepted ABI atoms, pinned tokenizer
rendering and model-visible metadata stripping are proven. No canonical truth/effect,
runtime, J-Space, HCU, EntityOS or training credit is minted here.
"""
from __future__ import annotations

import argparse
import importlib.util
import itertools
import json
import math
from collections import Counter
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent


def _load(name: str, filename: str):
    path = HERE / filename
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


L = _load("trigger2_shp_labelers_v1", "trigger2_semantic_hyperposition_reference_labelers_v1.py")
G = _load("trigger2_shp_transition_gate_v1", "trigger2_semantic_hyperposition_transition_gate_v1.py")

SCHEMA = "CLAY_TRIGGER2_SEMANTIC_HYPERPOSITION_TRANSITION_BLUEPRINT/v1"
ROW_SCHEMA = "ENTITYOS_HCU_TRAININGTRACE_CANDIDATE/v1"
TRANSITION_SCHEMA = "XENO_SEMANTIC_HYPERPOSITION_TRANSITION/v1"
MODEL = "Goekdeniz-Guelmez/Josiefied-Qwen3.5-0.8B-gabliterated-v1"
MODEL_REVISION = "591852bda6e1979f59e4b0f5ee2919697b12e936"
CLASSES = ("QUERY_TRUE", "QUERY_FALSE", "QUERY_UNKNOWN")
BRANCH_IDS = ("b0", "b1", "b2")
BRANCH_ORDERS = tuple(itertools.permutations(BRANCH_IDS))
CODEBOOK_PERMS = tuple(itertools.permutations(range(3)))
LAYOUTS = ("STATE_THEN_EVENT", "EVENT_THEN_STATE")
TRAIN_TEMPLATES = ("T1_NUMERIC_COMPARISON", "T2_SET_MEMBERSHIP")
VALIDATION_TEMPLATES = ("T3_ORDER_RELATION",)
ABI_SYMBOLS = tuple(f"ABI_ACCEPTED_ORDINAL:{i:02d}" for i in range(3))
ANTI_COLLAPSE = [
    "NO_MAJORITY_AS_TRUTH",
    "NO_SALIENCE_AS_PROBABILITY",
    "NO_RECURRENCE_AS_EVIDENCE",
    "NO_SILENT_BRANCH_DROP",
    "PROJECTION_IS_NOT_DELETION",
]


def semantic_case(template: str, klass: str) -> tuple[str, str]:
    if template == "T1_NUMERIC_COMPARISON":
        query = "Register r is greater than 5."
        evidence = {
            "QUERY_TRUE": "Register r has value 7.",
            "QUERY_FALSE": "Register r has value 3.",
            "QUERY_UNKNOWN": "Register s has value 7; no value for register r is given.",
        }
    elif template == "T2_SET_MEMBERSHIP":
        query = "Marker m belongs to set K."
        evidence = {
            "QUERY_TRUE": "Set K explicitly contains marker m.",
            "QUERY_FALSE": "Set K explicitly excludes marker m.",
            "QUERY_UNKNOWN": "Set K contains marker n; membership of marker m is unspecified.",
        }
    elif template == "T3_ORDER_RELATION":
        query = "Node p occurs before node q."
        evidence = {
            "QUERY_TRUE": "The order record states p before q.",
            "QUERY_FALSE": "The order record states q before p.",
            "QUERY_UNKNOWN": "The order record states p before z; relation between p and q is unspecified.",
        }
    else:
        raise ValueError(template)
    return evidence[klass], query


def _branch(branch_id: str, value: str, family: str) -> dict[str, Any]:
    epistemic = "HYPOTHESIS" if value != "QUERY_FALSE" else "COUNTERHYPOTHESIS"
    return {
        "branch_id": branch_id,
        "v_semantic_value": value,
        "K_context_predicate": "CURRENT_SYNTHETIC_QUERY",
        "evidence_for": [],
        "evidence_against": [],
        "F_falsifier": f"explicit_discriminator_against:{value}",
        "T_validity_scope": "SYNTHETIC_EPISODE_ONLY",
        "A_origin_provenance": family,
        "sigma_epistemic_status": epistemic,
        "projection_visibility": "VISIBLE",
        "validity": "LIVE",
    }


def state_before(order: tuple[str, ...], family: str) -> dict[str, Any]:
    values = {"b0": "QUERY_TRUE", "b1": "QUERY_FALSE", "b2": "QUERY_UNKNOWN"}
    return {
        "schema": L.STATE_SCHEMA,
        "query_id": family,
        "canonical_truth_allowed": False,
        "direct_effect_authority": False,
        "branches": [_branch(bid, values[bid], family) for bid in order],
        "projection": {"operation": "NONDESTRUCTIVE_VIEW", "context": "CURRENT_SYNTHETIC_QUERY"},
    }


def observation_for(klass: str, family: str, template: str) -> dict[str, Any]:
    target = {"QUERY_TRUE": "b0", "QUERY_FALSE": "b1", "QUERY_UNKNOWN": "b2"}[klass]
    if klass == "QUERY_TRUE":
        effect, epistemic = "PROVE", "SYNTHETIC_PROOF"
    elif klass == "QUERY_FALSE":
        effect, epistemic = "PROVE", "SYNTHETIC_PROOF"
    else:
        effect, epistemic = "SUPPORT", "UNKNOWN"
    return {
        "schema": L.OBS_SCHEMA,
        "observation_id": f"obs:{family}",
        "canonical_truth_allowed": False,
        "direct_effect_authority": False,
        "effect": effect,
        "target_branch_ids": [target],
        "evidence": {
            "evidence_id": f"e:{family}",
            "provenance_ancestry_id": f"ancestry:{template}:{klass}",
            "independence_group": f"independent:{family}",
            "epistemic_type": epistemic,
        },
    }


def discriminators_for(family: str) -> list[dict[str, Any]]:
    return [
        {
            "schema": L.DISC_SCHEMA,
            "discriminator_id": f"d_full:{family}",
            "canonical_truth_allowed": False,
            "direct_effect_authority": False,
            "admissible": True,
            "separates_pairs": [["b0", "b1"], ["b0", "b2"], ["b1", "b2"]],
            "cost_rank": 2,
        },
        {
            "schema": L.DISC_SCHEMA,
            "discriminator_id": f"d_partial:{family}",
            "canonical_truth_allowed": False,
            "direct_effect_authority": False,
            "admissible": True,
            "separates_pairs": [["b0", "b1"]],
            "cost_rank": 0,
        },
    ]


def salience_items_for(family: str) -> list[dict[str, Any]]:
    return [
        {"item_id": f"current:{family}", "actionability_rank": 0, "scope_rank": 0, "freshness_rank": 0},
        {"item_id": f"background:{family}", "actionability_rank": 2, "scope_rank": 1, "freshness_rank": 1},
    ]


def render_prompt(
    template: str,
    evidence: str,
    query: str,
    before: dict[str, Any],
    symbols: tuple[str, str, str],
    mapping: tuple[int, int, int],
    layout: str,
) -> str:
    codebook = "\n".join(f"{CLASSES[i]} => {symbols[mapping[i]]}" for i in range(3))
    branch_lines = "\n".join(
        f"{b['branch_id']}: value={b['v_semantic_value']}; status={b['sigma_epistemic_status']}; validity={b['validity']}"
        for b in before["branches"]
    )
    state_block = (
        "<HYPERPOSITION_STATE projection=non_destructive collapse=proof_or_discriminator_only>\n"
        + branch_lines
        + "\n</HYPERPOSITION_STATE>"
    )
    event_block = f"EVIDENCE: {evidence}\nQUERY: {query}"
    body = state_block + "\n" + event_block if layout == "STATE_THEN_EVENT" else event_block + "\n" + state_block
    return (
        f"{body}\n<EPISODE_CODEBOOK>\n{codebook}\n</EPISODE_CODEBOOK>\n"
        "Update the live semantic Hyperposition without using branch order, repetition or salience as truth. "
        "Return exactly the episode codebook symbol for the resulting semantic class."
    )


def build_row(template: str, split: str, klass: str, order: tuple[str, ...], mapping: tuple[int, ...], layout: str) -> dict[str, Any]:
    oi = BRANCH_ORDERS.index(order)
    mi = CODEBOOK_PERMS.index(mapping)
    family = f"SHP_TRANS_{template}_{klass}_O{oi}_M{mi}_{layout}"
    before = state_before(order, family)
    obs = observation_for(klass, family, template)
    update = L.U_update(before, obs)
    assert update["pass"], update
    after = update["state_after"]
    # PROVE transitions resolve through the explicit synthetic-proof validity emitted
    # by U_update. UNKNOWN/SUPPORT stays unresolved. No branch deletion is performed.
    resolution = L.D_resolve(after, None)
    assert resolution["pass"], resolution
    discriminators = discriminators_for(family)
    dorder = L.U_d_test_order(after, discriminators)
    assert dorder["pass"], dorder
    salience_items = salience_items_for(family)
    salience = L.f_salience_rank(salience_items)
    assert salience["pass"], salience
    evidence, query = semantic_case(template, klass)
    ci = CLASSES.index(klass)
    target = ABI_SYMBOLS[mapping[ci]]
    row = {
        "schema": ROW_SCHEMA,
        "family_id": family,
        "split": split,
        "split_unit": "SEMANTIC_TEMPLATE_FAMILY_AND_PROVENANCE_ANCESTRY",
        "selected_using_holdout": False,
        "canonical_truth_allowed": False,
        "direct_effect_authority": False,
        "evidence_class": "METHOD_ONLY",
        "reality_level": "R2",
        "model": MODEL,
        "model_revision": MODEL_REVISION,
        "prompt": render_prompt(template, evidence, query, before, ABI_SYMBOLS, mapping, layout),
        "target": target,
        "target_type": "EPISODE_LOCAL_CODEBOOK_SYMBOL",
        "semantic_class_reference_only": klass,
        "training_eligible": False,
        "render_status": "BLOCKED_UNTIL_EXACT_ACCEPTED_ABI_ATOMS_PINNED_TOKENIZER_AND_MODEL_VISIBLE_METADATA_STRIP_GATE",
        "semantic_hyperposition_transition": {
            "schema": TRANSITION_SCHEMA,
            "canonical_truth_allowed": False,
            "direct_effect_authority": False,
            "state_before": before,
            "observation": obs,
            "state_after": after,
            "resolution": resolution["resolution"],
            "discriminator_outcome": None,
            "discriminators": discriminators,
            "discriminator_order": dorder["ordering"],
            "salience_items": salience_items,
            "salience_order": salience["ranking"],
            "projection_operation": "NONDESTRUCTIVE_VIEW",
            "anti_collapse": ANTI_COLLAPSE,
            "codebook_mapping_reference_only": list(mapping),
            "branch_order_reference_only": list(order),
            "layout_reference_only": layout,
        },
    }
    verdict = G.adjudicate(row)
    assert verdict["semantic_hyperposition_transition_pass"], verdict
    return row


def build_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    specs = [*((t, "TRAIN") for t in TRAIN_TEMPLATES), *((t, "VALIDATION") for t in VALIDATION_TEMPLATES)]
    for template, split in specs:
        for klass in CLASSES:
            for order in BRANCH_ORDERS:
                for mapping in CODEBOOK_PERMS:
                    for layout in LAYOUTS:
                        rows.append(build_row(template, split, klass, order, mapping, layout))
    return rows


def mi(rows: list[dict[str, Any]], fa, fb) -> float:
    n = len(rows)
    joint = Counter((fa(r), fb(r)) for r in rows)
    a = Counter(fa(r) for r in rows)
    b = Counter(fb(r) for r in rows)
    return sum((v / n) * math.log2((v / n) / ((a[x] / n) * (b[y] / n))) for (x, y), v in joint.items())


def selftest(rows: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    rows = build_rows() if rows is None else rows
    train = [r for r in rows if r["split"] == "TRAIN"]
    val = [r for r in rows if r["split"] == "VALIDATION"]
    assert (len(train), len(val), len(rows)) == (432, 216, 648)
    assert all(r["training_eligible"] is False for r in rows)
    assert all(G.adjudicate(r)["semantic_hyperposition_transition_pass"] for r in rows)

    for template in TRAIN_TEMPLATES + VALIDATION_TEMPLATES:
        rr = [r for r in rows if template in r["family_id"]]
        cells = Counter(
            (
                r["semantic_class_reference_only"],
                tuple(r["semantic_hyperposition_transition"]["branch_order_reference_only"]),
                tuple(r["semantic_hyperposition_transition"]["codebook_mapping_reference_only"]),
                r["semantic_hyperposition_transition"]["layout_reference_only"],
            )
            for r in rr
        )
        assert len(cells) == 3 * 6 * 6 * 2 and set(cells.values()) == {1}

    metrics = {
        "semantic_class__target_symbol": mi(train, lambda r: r["semantic_class_reference_only"], lambda r: r["target"]),
        "semantic_class__branch_order": mi(train, lambda r: r["semantic_class_reference_only"], lambda r: tuple(r["semantic_hyperposition_transition"]["branch_order_reference_only"])),
        "target_symbol__branch_order": mi(train, lambda r: r["target"], lambda r: tuple(r["semantic_hyperposition_transition"]["branch_order_reference_only"])),
        "target_symbol__layout": mi(train, lambda r: r["target"], lambda r: r["semantic_hyperposition_transition"]["layout_reference_only"]),
    }
    assert all(abs(x) < 1e-12 for x in metrics.values())
    return {
        "schema": SCHEMA,
        "pass": True,
        "rows": len(rows),
        "train": len(train),
        "validation": len(val),
        "holdout_rendered": 0,
        "branch_orders": len(BRANCH_ORDERS),
        "codebook_permutations": len(CODEBOOK_PERMS),
        "layouts": len(LAYOUTS),
        "conditional_full_cross_by_construction": True,
        "shortcut_mi_bits": metrics,
        "training_eligible": False,
        "accepted_dataset_tokens_minted": 0,
        "blockers": [
            "exact accepted 46-atom ABI strings not yet bound into rendered targets",
            "exact pinned-tokenizer one-token/position checks not yet proven on rendered bytes",
            "reference-only audit metadata must be stripped from model-visible serialization",
            "fresh holdout families must be allocated only after pilot recipe freeze",
        ],
        "credit_scope": "DETERMINISTIC_SOURCE_BLUEPRINT_ONLY",
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--split", choices=("all", "train", "validation"), default="all")
    args = ap.parse_args()
    rows = build_rows()
    if args.selftest:
        print(json.dumps(selftest(rows), sort_keys=True))
        return
    selected = rows if args.split == "all" else [r for r in rows if r["split"] == args.split.upper()]
    for row in selected:
        print(json.dumps(row, separators=(",", ":"), ensure_ascii=False))


if __name__ == "__main__":
    main()
