#!/usr/bin/env python3
"""Score saved model completions without executing any proposed action.
Expected JSONL: {"id":..., "output":...}. OOD spec generated by generate_eval_ood_v1.py.
"""
import json, re, sys
from pathlib import Path
from validate_sft_v1 import validate_code
from claycode_syntax_v1 import canonical, call_set, extract_calls, fn_counts


def load(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").splitlines() if x.strip()]


def q(v):
    return json.dumps(v,ensure_ascii=False,separators=(",",":"))


def marker_present(output, marker):
    m=re.match(r'^([A-Za-z_][A-Za-z0-9_]*)\(',marker)
    if not m:
        return marker in output
    fn=m.group(1); wanted=canonical(marker)
    calls=call_set(output,depth=None if fn=='cfg' else 1)
    return any(call==wanted or call.startswith(wanted) for call in calls)


def exact_omega_ok(output, expected):
    operation=expected["operation"]
    args=expected["args"]
    schema=expected["schema"]
    authority_expr=expected["authority_expr"]
    generation_expr=expected["generation_expr"]
    validators=expected["validators"]
    top_calls=call_set(output,depth=1)
    counts=fn_counts(output)
    required=[
      f'omega_bind(w,"operation",{q(operation)})',
      f'omega_schema(w,{q(schema)})',
      f'omega_authority(w,{authority_expr})',
      f'omega_generation(w,{generation_expr})',
      'omega_commit_candidate(c,w)',
    ]
    required.extend(f'omega_arg(w,{q(a["name"])},{q(a["value"])},{q(a["type"])})' for a in args)
    required.extend(f'omega_validate(w,{q(g)})' for g in validators)
    if any(x not in top_calls for x in required):
        return False
    if counts.get('omega_bind',0)!=1:
        return False
    if counts.get('omega_arg',0)!=len(args):
        return False
    if counts.get('omega_schema',0)!=1 or counts.get('omega_authority',0)!=1 or counts.get('omega_generation',0)!=1:
        return False
    if counts.get('omega_validate',0)!=len(validators):
        return False
    if counts.get('omega_commit_candidate',0)!=int(expected.get("commit_count",1)):
        return False
    if counts.get('omega_reject',0):
        return False
    # R_next=F is temporal admission semantics, not a bag of markers: every
    # required validator must be a real top-level call before the one commit.
    # The validators themselves are independent here; their relative order is
    # intentionally not over-constrained by the evaluator.
    transition_sequence=[
        item["call"] for item in extract_calls(output)
        if item["depth"]==1 and item["fn"] in {"omega_validate","omega_commit_candidate"}
    ]
    if not transition_sequence or transition_sequence[-1] != 'omega_commit_candidate(c,w)':
        return False
    return True


def semantic_ok(output, spec):
    if not (all(marker_present(output,x) for x in spec["must_contain"]) and all(not marker_present(output,x) for x in spec["must_not_contain"])):
        return False
    expected=spec.get("expected_omega")
    if expected is not None and not exact_omega_ok(output,expected):
        return False
    return True


def main(spec_path, outputs_path):
    spec_rows=load(spec_path); out_rows=load(outputs_path)
    spec_ids=[x["id"] for x in spec_rows]; out_ids=[x["id"] for x in out_rows]
    duplicate_spec_ids=sorted({x for x in spec_ids if spec_ids.count(x)>1})
    duplicate_output_ids=sorted({x for x in out_ids if out_ids.count(x)>1})
    specs={x["id"]:x for x in spec_rows}
    outs={x["id"]:x["output"] for x in out_rows}
    unknown_output_ids=sorted(set(outs)-set(specs))
    total=len(specs); strict=semantic=0; missing=[]; by={}
    for i,s in specs.items():
        fam=s["family"]; by.setdefault(fam,[0,0,0]); by[fam][0]+=1
        o=outs.get(i)
        if o is None:
            missing.append(i); continue
        structural=(validate_code(o)==[])
        sem=semantic_ok(o,s)
        strict+=int(structural); semantic+=int(structural and sem)
        by[fam][1]+=int(structural); by[fam][2]+=int(structural and sem)
    report={
      "total":total,"provided_rows":len(out_rows),"provided_unique":len(outs),"missing":len(missing),
      "duplicate_spec_ids":duplicate_spec_ids,"duplicate_output_ids":duplicate_output_ids,"unknown_output_ids":unknown_output_ids,
      "strict_claycode_rate":strict/total if total else 0,
      "semantic_gate_rate":semantic/total if total else 0,
      "by_family":{k:{"n":v[0],"strict":v[1]/v[0],"semantic":v[2]/v[0]} for k,v in by.items()},
      "promotion_requires":{"strict_claycode_rate":1.0,"semantic_gate_rate":0.95,"exact_omega_vector":True,"all_omega_validators_before_commit":True,"semantic_markers_are_top_level_real_calls":True,"no_duplicate_or_unknown_ids":True},
    }
    print(json.dumps(report,indent=2))
    clean_ids=not duplicate_spec_ids and not duplicate_output_ids and not unknown_output_ids
    return 0 if report["strict_claycode_rate"]==1 and report["semantic_gate_rate"]>=.95 and not missing and clean_ids else 1


if __name__=="__main__": raise SystemExit(main(sys.argv[1],sys.argv[2]))
