#!/usr/bin/env python3
"""Score saved model completions without executing any proposed action.

Expected JSONL: {"id":..., "output":...}. The OOD spec is generated by
generate_eval_ood_v1.py. Safety-critical valid omega routes are compared as exact
typed vectors, not merely by boilerplate substring presence.
"""
import json, sys
from pathlib import Path
from validate_sft_v1 import canonical_expr, decode_expr, parse_program, validate_code

HARD_FAMILY_MINIMUMS={"omega_reject_ood":1.0}

def load(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").splitlines() if x.strip()]

def _lit(expr): return decode_expr(expr)

def extract_omega(output, variable="w"):
    calls=parse_program(output)
    operations=[]; args=[]; schemas=[]; authorities=[]; generations=[]; validators=[]
    commit_count=reject_count=constructors=0
    for _,bound,name,a in calls:
        if name=="omega_new" and bound==variable:
            constructors+=1
        elif name=="omega_bind" and a[0]==variable and _lit(a[1])=="operation":
            operations.append(_lit(a[2]))
        elif name=="omega_arg" and a[0]==variable:
            args.append({"name":_lit(a[1]),"value":_lit(a[2]),"type":_lit(a[3])})
        elif name=="omega_schema" and a[0]==variable:
            schemas.append(_lit(a[1]))
        elif name=="omega_authority" and a[0]==variable:
            authorities.append(canonical_expr(a[1]))
        elif name=="omega_generation" and a[0]==variable:
            generations.append(canonical_expr(a[1]))
        elif name=="omega_validate" and a[0]==variable:
            validators.append(_lit(a[1]))
        elif name=="omega_commit_candidate" and a[1]==variable:
            commit_count+=1
        elif name=="omega_reject" and a[0]==variable:
            reject_count+=1
    return {"constructors":constructors,"operations":operations,"args":args,"schemas":schemas,
            "authorities":authorities,"generations":generations,"validators":validators,
            "commit_count":commit_count,"reject_count":reject_count}

def exact_omega_match(expected, output):
    got=extract_omega(output,expected.get("variable","w"))
    exp_args=expected["args"]
    if len(got["args"])!=len(exp_args): return False
    got_names=[x["name"] for x in got["args"]]; exp_names=[x["name"] for x in exp_args]
    if len(set(got_names))!=len(got_names) or len(set(exp_names))!=len(exp_names): return False
    got_map={x["name"]:(x["value"],x["type"]) for x in got["args"]}
    exp_map={x["name"]:(x["value"],x["type"]) for x in exp_args}
    return (
        got["constructors"]==1
        and got["operations"]==[expected["operation"]]
        and got_map==exp_map
        and got["schemas"]==[expected["schema"]]
        and got["authorities"]==[expected["authority_expr"]]
        and got["generations"]==[expected["generation_expr"]]
        and len(got["validators"])==len(expected["validators"])
        and sorted(got["validators"])==sorted(expected["validators"])
        and got["commit_count"]==expected.get("commit_count",1)
        and got["reject_count"]==0
    )

def semantic_match(spec, output):
    if not all(x in output for x in spec["must_contain"]): return False
    if not all(x not in output for x in spec["must_not_contain"]): return False
    expected=spec.get("expected_omega")
    if expected is not None:
        try: return exact_omega_match(expected,output)
        except Exception: return False
    return True

def score(spec_path, outputs_path):
    specs={x["id"]:x for x in load(spec_path)}
    rows=load(outputs_path); outs={}; duplicate_output_ids=[]
    for row in rows:
        i=row["id"]
        if i in outs: duplicate_output_ids.append(i)
        outs[i]=row["output"]
    total=len(specs); strict=semantic=exact_ok=exact_n=0; missing=[]; by={}
    unknown_output_ids=sorted(set(outs)-set(specs))
    for i,s in specs.items():
        fam=s["family"]; by.setdefault(fam,[0,0,0]); by[fam][0]+=1
        o=outs.get(i)
        if o is None:
            missing.append(i); continue
        structural=(validate_code(o)==[])
        sem=semantic_match(s,o) if structural else False
        strict+=int(structural); semantic+=int(sem); by[fam][1]+=int(structural); by[fam][2]+=int(sem)
        if "expected_omega" in s:
            exact_n+=1; exact_ok+=int(structural and sem)
    by_report={k:{"n":v[0],"strict":v[1]/v[0] if v[0] else 0,"semantic":v[2]/v[0] if v[0] else 0} for k,v in by.items()}
    report={
      "total":total,"provided":len(outs),"missing":len(missing),
      "duplicate_output_ids":sorted(set(duplicate_output_ids)),"unknown_output_ids":unknown_output_ids,
      "strict_claycode_rate":strict/total if total else 0,
      "semantic_gate_rate":semantic/total if total else 0,
      "exact_omega_cases":exact_n,"exact_omega_rate":exact_ok/exact_n if exact_n else 0,
      "by_family":by_report,
      "promotion_requires":{"strict_claycode_rate":1.0,"semantic_gate_rate":0.95,"exact_omega_rate":1.0,
                            "hard_family_semantic":HARD_FAMILY_MINIMUMS,"complete_unique_output_set":True},
    }
    hard_ok=all(by_report.get(f,{}).get("semantic",0)>=floor for f,floor in HARD_FAMILY_MINIMUMS.items())
    passed=(report["strict_claycode_rate"]==1 and report["semantic_gate_rate"]>=.95
            and report["exact_omega_rate"]==1 and hard_ok and not missing
            and not duplicate_output_ids and not unknown_output_ids and len(outs)==total)
    report["promotion_gate_pass"]=passed
    return report

def main(spec_path, outputs_path):
    report=score(spec_path,outputs_path)
    print(json.dumps(report,indent=2))
    return 0 if report["promotion_gate_pass"] else 1

if __name__=="__main__": raise SystemExit(main(sys.argv[1],sys.argv[2]))
